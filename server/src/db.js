async function applyMigrations() {
  await query(`
    CREATE TABLE IF NOT EXISTS schema_migrations (
      id TEXT PRIMARY KEY,
      applied_at TEXT NOT NULL
    );
  `)

  const applied = await query('SELECT id FROM schema_migrations')
  const appliedSet = new Set(applied.rows.map((r) => r.id))

  for (const m of MIGRATIONS) {
    if (appliedSet.has(m.id)) continue
    const appliedAt = new Date().toISOString()
    await withTx(async (client) => {
      await client.query(m.sql)
      await client.query('INSERT INTO schema_migrations (id, applied_at) VALUES ($1, $2)', [m.id, appliedAt])
    })
  }
}

async function seedDefaults() {
  const now = new Date().toISOString()
  const v = await query('SELECT COUNT(*)::int AS c FROM vehicle_types')
  const s = await query('SELECT COUNT(*)::int AS c FROM service_types')

  if ((v.rows[0]?.c ?? 0) === 0) {
    const vehicles = ['Sedan', 'SUV', 'Bakkie', 'Minivan']
    for (let i = 0; i < vehicles.length; i += 1) {
      await query('INSERT INTO vehicle_types (name, sort_order, active) VALUES ($1, $2, 1) ON CONFLICT (name) DO NOTHING', [
        vehicles[i],
        i,
      ])
    }
  }

  if ((s.rows[0]?.c ?? 0) === 0) {
    const services = ['Basic Wash', 'Full Wash', 'Premium Detail']
    for (let i = 0; i < services.length; i += 1) {
      await query('INSERT INTO service_types (name, sort_order, active) VALUES ($1, $2, 1) ON CONFLICT (name) DO NOTHING', [
        services[i],
        i,
      ])
    }
  }

  const p = await query('SELECT COUNT(*)::int AS c FROM price_matrix')
  if ((p.rows[0]?.c ?? 0) !== 0) return

  const vehicles = await query('SELECT id, name FROM vehicle_types ORDER BY sort_order ASC, id ASC')
  const services = await query('SELECT id, name FROM service_types ORDER BY sort_order ASC, id ASC')
  const defaultPrices = new Map([
    ['Sedan|Basic Wash', 4000],
    ['Sedan|Full Wash', 6000],
    ['Sedan|Premium Detail', 9000],
    ['SUV|Basic Wash', 5000],
    ['SUV|Full Wash', 7500],
    ['SUV|Premium Detail', 11000],
    ['Bakkie|Basic Wash', 5500],
    ['Bakkie|Full Wash', 8000],
    ['Bakkie|Premium Detail', 12000],
    ['Minivan|Basic Wash', 6000],
    ['Minivan|Full Wash', 8500],
    ['Minivan|Premium Detail', 13000],
  ])

  await withTx(async (client) => {
    for (const vt of vehicles.rows) {
      for (const st of services.rows) {
        const key = `${vt.name}|${st.name}`
        const price = defaultPrices.get(key) ?? 0
        await client.query(
          'INSERT INTO price_matrix (vehicle_type_id, service_type_id, price_cents, updated_at) VALUES ($1, $2, $3, $4) ON CONFLICT (vehicle_type_id, service_type_id) DO NOTHING',
          [vt.id, st.id, price, now],
        )
      }
    }
  })
}

export async function initDb() {
  await applyMigrations()
  await seedDefaults()
}

export async function isBootstrapped() {
  const r = await query('SELECT COUNT(*)::int AS c FROM users')
  return (r.rows[0]?.c ?? 0) > 0
}
